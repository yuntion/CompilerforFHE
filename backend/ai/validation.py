"""Real differential validation for runners built from native schedule JSON.

The caller must establish that the candidate was generated by the trusted native
schedule compiler. This module separates client commands from evaluation; it is
not an operating-system sandbox for arbitrary executables or C++ source.
"""
from __future__ import annotations

import math
import os
from pathlib import Path
import subprocess

import numpy as np
import onnx
from onnx.reference import ReferenceEvaluator

from backend.execution import _read_values, _write_values
from backend.toolchain import command
from .artifacts import digest, verify_artifact, write_json
from .protocol import parse_json


_COUNTERS = {
    "add", "sub", "multiply_plain", "multiply_cipher", "rescale", "mod_switch",
    "relinearize", "rotations", "add_plain", "materializations", "ckks_to_logic",
    "logic_bootstrap", "logic_to_ckks", "select", "input_ciphertexts", "output_ciphertexts",
}


class ValidationInfrastructureError(RuntimeError):
    """An execution environment failure cannot be repaired by changing a plan."""


def _invoke(args, config, log, *, cwd=None, runtime=False):
    try:
        text, wall = command(args, config, cwd=cwd, log=log)
    except subprocess.TimeoutExpired as error:
        stdout, stderr = error.stdout or "", error.stderr or ""
        if isinstance(stdout, bytes):
            stdout = stdout.decode("utf-8", errors="replace")
        if isinstance(stderr, bytes):
            stderr = stderr.decode("utf-8", errors="replace")
        log.write_text(stdout+stderr+"\nprocess timed out\n", encoding="utf-8")
        raise ValidationInfrastructureError(f"runner timed out; see {log}") from error
    if not runtime:
        return {"wall_seconds": wall}
    lines = text.strip().splitlines()
    value = parse_json(lines[-1]) if lines else None
    if not isinstance(value, dict):
        raise RuntimeError(f"runner emitted no JSON runtime record; see {log}")
    return {"wall_seconds": wall, "runtime": value}


def _counts(record):
    runtime = record["runtime"]
    if runtime.get("phase") != "evaluate":
        raise RuntimeError("runner returned the wrong evaluation phase")
    seconds = runtime.get("seconds")
    if isinstance(seconds, bool) or not isinstance(seconds, (int, float)) or not math.isfinite(seconds) or seconds < 0:
        raise RuntimeError("runner returned invalid evaluator timing")
    counts = {name: runtime[name] for name in _COUNTERS if name in runtime}
    if not counts or any(type(value) is not int or value < 0 for value in counts.values()):
        raise RuntimeError("runner returned invalid or missing operation counters")
    return counts


def _input_dtypes(model, inputs):
    graph_inputs = {value.name: value for value in model.graph.input}
    result = {}
    for info in inputs:
        value = graph_inputs[info["name"]]
        dtype = np.dtype(onnx.helper.tensor_dtype_to_np_dtype(value.type.tensor_type.elem_type))
        if dtype not in (np.dtype("float32"), np.dtype("float64")):
            raise RuntimeError("validation requires floating-point ONNX inputs")
        result[info["name"]] = dtype
    return result


def _default_cases(manifest, dtypes, policy):
    bound = policy["input_bound"]
    rng = np.random.default_rng(policy["seed"])
    logic = manifest["backend"] == "openfhe-cross" and manifest.get("logic_comparisons", 0)
    names = ["positive", "negative", "alternating", "random"] if logic else [
        "zero", "positive", "negative", "alternating", "random"]
    result = []
    for name in names:
        values = {}
        for info in manifest["inputs"]:
            shape, size = tuple(info["shape"]), info["count"]
            typed_bound = np.asarray(bound, dtype=dtypes[info["name"]])
            if float(typed_bound) > bound:
                typed_bound = np.nextafter(typed_bound, np.asarray(0, dtype=typed_bound.dtype))
            case_bound = float(typed_bound)
            if name == "zero":
                value = np.zeros(size)
            elif name == "positive":
                value = np.full(size, case_bound)
            elif name == "negative":
                value = np.full(size, -case_bound)
            elif name == "alternating":
                value = np.where(np.arange(size) % 2, -case_bound, case_bound)
            elif logic:
                # This avoids a near-zero input comparison in common sign/ReLU
                # tasks. It cannot guarantee margins at arbitrary internal nodes.
                value = rng.choice([-1.0, 1.0], size=size)*rng.uniform(case_bound/4, case_bound, size=size)
            else:
                value = rng.uniform(-case_bound, case_bound, size=size)
            values[info["name"]] = value.reshape(shape).astype(dtypes[info["name"]])
        result.append((name, values))
    return result


def _feeds(values, manifest, dtypes, bound):
    if not isinstance(values, dict) or set(values) != {info["name"] for info in manifest["inputs"]}:
        raise RuntimeError("validation input names differ from the frozen ABI")
    feeds, flat = {}, []
    for info in manifest["inputs"]:
        try:
            source = np.asarray(values[info["name"]])
            if source.dtype.kind == "c":
                raise ValueError("complex input")
            value = source.astype(dtypes[info["name"]])
        except (ValueError, TypeError, OverflowError) as error:
            raise RuntimeError(f"validation input is not a real tensor: {info['name']}") from error
        if list(value.shape) != info["shape"] or not np.isfinite(value).all():
            raise RuntimeError(f"invalid validation input shape/values: {info['name']}")
        if np.any(np.abs(value.astype(np.float64)) > bound):
            raise RuntimeError(f"validation input exceeds public bound: {info['name']}")
        feeds[info["name"]] = value
        flat.extend(value.astype(np.float64).flat)
    return feeds, flat


def _outputs(path, infos):
    flat = _read_values(path)
    if flat.size != sum(info["count"] for info in infos) or not np.isfinite(flat).all():
        raise RuntimeError("decrypted output count or finite-value check failed")
    return {info["name"]: flat[info["offset"]:info["offset"]+info["count"]].reshape(info["shape"])
            for info in infos}


def _error(actual, expected, atol, rtol):
    """Compare outputs already checked by decoding or plaintext evaluation."""
    delta = np.abs(actual.astype(np.float64)-expected.astype(np.float64))
    relative = delta/np.maximum(np.abs(expected), np.finfo(np.float64).eps)
    maximum, relmax = float(np.max(delta)), float(np.max(relative))
    if not np.isfinite([maximum, relmax]).all():
        raise RuntimeError("validation error metric is non-finite")
    return {"max_abs_error": maximum, "max_relative_error": relmax,
            "relative_denominator_floor": float(np.finfo(np.float64).eps),
            "passed": bool(np.allclose(actual, expected, atol=atol, rtol=rtol))}


def _summary(records):
    seconds = [record["runtime"]["seconds"] for record in records]
    wall = [record["wall_seconds"] for record in records]
    return {"samples_seconds": seconds, "wall_samples_seconds": wall,
            "median_seconds": float(np.median(seconds)), "p95_seconds": float(np.percentile(seconds, 95)),
            "median_wall_seconds": float(np.median(wall)), "p95_wall_seconds": float(np.percentile(wall, 95))}


def validate_encrypted(artifact: Path, candidate_runner: Path, task: dict,
                       output: Path, config: dict, *, cases=None) -> dict:
    """Validate a trusted schedule build after the driver verifies its task.

    A successful result records evidence only. Candidate selection belongs to the
    driver; INSECURE_TOY can never satisfy policy_passed or become selectable.
    """
    artifact, candidate_runner, output = Path(artifact).resolve(), Path(candidate_runner).resolve(), Path(output).resolve()
    if output == artifact or output.is_relative_to(artifact):
        raise RuntimeError("validation output must be separate from the frozen artifact")
    if output.exists() and any(output.iterdir()):
        raise RuntimeError("validation output must be empty")
    output.mkdir(parents=True, exist_ok=True)
    client, server, logs = output/"client", output/"server", output/"logs"
    logs.mkdir()
    report = {"status": "validating", "validation_performed": False,
              "functional_passed": False, "policy_passed": False, "measured": False,
              "selectable": False, "cases": [], "task_hash": task.get("task_hash"),
              "validation_directory": str(output)}
    stage = "identity"
    try:
        policy = task["validation_policy"]
        manifest = verify_artifact(artifact, task, config)
        suffix = ".exe" if os.name == "nt" else ""
        trusted = artifact/"build"/"bin"/("model-runner"+suffix)
        if not trusted.is_file() or not candidate_runner.is_file():
            raise RuntimeError("reference or candidate runner is missing")
        report["source_identity"] = {
            "model_sha256": manifest["model_sha256"], "reference_header_sha256": manifest["artifact_hashes"]["model.hpp"],
            "reference_runner_sha256": manifest["artifact_hashes"][f"build/bin/model-runner{suffix}"],
            "candidate_runner_sha256": digest(candidate_runner),
            "library_revision": task.get("library_revision"), "backend_context": task.get("backend_context"),
        }
        report["backend"] = manifest["backend"]
        report["validation_policy"] = policy.copy()
        report["approximation"] = task.get("approximation", {})
        model = onnx.load(str(artifact/"model.onnx"))
        evaluator = ReferenceEvaluator(model)
        dtypes = _input_dtypes(model, manifest["inputs"])
        named_cases = (_default_cases(manifest, dtypes, policy) if cases is None else
                       [(f"supplied_{index}", values) for index, values in enumerate(cases)])
        if not named_cases:
            raise RuntimeError("at least one independent validation case is required")
        stage = "keygen"
        args = [trusted, "keygen", client, server]
        if manifest["backend"] == "openfhe-cross":
            args.extend(["--comparison-scale", str(policy["comparison_scale"])])
            if policy["insecure_demo"]:
                args.append("--insecure-demo")
        keygen = _invoke(args, config, logs/"keygen.log", runtime=True)
        actual = keygen["runtime"]
        if actual.get("phase") != "keygen":
            raise RuntimeError("trusted runner returned the wrong key generation phase")
        expected_depth = max(2 if manifest["backend"] == "openfhe-cross" else 1,
                             task["contract"]["openfhe_depth" if manifest["backend"] == "openfhe-cross" else "multiplicative_depth"])
        if actual.get("depth") != expected_depth or type(actual.get("ring_dimension")) is not int or actual["ring_dimension"] <= 0:
            raise RuntimeError("actual depth/ring dimension does not match the trusted parameter plan")
        if manifest["backend"] == "openfhe-cross":
            if actual.get("security_profile") != policy["security_profile"]:
                raise RuntimeError("actual OpenFHE security profile differs from policy")
            if not math.isclose(actual.get("comparison_scale", float("nan")), policy["comparison_scale"], rel_tol=5e-6, abs_tol=1e-12):
                raise RuntimeError("reported comparison scale differs from the frozen policy")
        elif actual.get("security_bits") != 128 or policy["security_profile"] != "tc128":
            raise RuntimeError("actual CKKS security profile differs from tc128 policy")
        # These files are the same throughout every reference/candidate run.
        bundle_hashes = {path.name: digest(path) for path in server.iterdir() if path.is_file()}
        if any("secret" in name.lower() for name in bundle_hashes):
            raise RuntimeError("trusted key generation placed private key material in the server directory")
        report["actual_parameters"] = {"keygen": actual, "keygen_wall_seconds": keygen["wall_seconds"],
                                       "server_bundle_hashes": bundle_hashes,
                                       "requested_comparison_scale": policy["comparison_scale"],
                                       "shared_keygen_count": 1}

        def integrity():
            for name, expected in bundle_hashes.items():
                if digest(server/name) != expected:
                    raise RuntimeError(f"frozen public/evaluation material changed: {name}")
            if digest(trusted) != report["source_identity"]["reference_runner_sha256"] or digest(candidate_runner) != report["source_identity"]["candidate_runner_sha256"]:
                raise RuntimeError("runner identity changed during validation")

        def evaluate(runner, input_path, output_path, log_name):
            value = _invoke([runner, "evaluate", server, input_path, output_path],
                            config, logs/log_name, cwd=server, runtime=True)
            value["counts"] = _counts(value)
            return value

        stage = "functional"
        report["validation_performed"] = True
        last_input, last_counts = None, None
        for index, (name, values) in enumerate(named_cases):
            feeds, flat = _feeds(values, manifest, dtypes, policy["input_bound"])
            try:
                expected_values = evaluator.run([info["name"] for info in manifest["outputs"]], feeds)
            except Exception as error:
                # ONNX diagnostics can include tensor contents. Keep them out
                # of feedback that may subsequently be sent to the provider.
                raise RuntimeError(f"independent plaintext evaluation failed for {name}: {type(error).__name__}") from error
            expected = {}
            for info, value in zip(manifest["outputs"], expected_values):
                value = np.asarray(value, dtype=np.float64)
                if list(value.shape) != info["shape"] or not np.isfinite(value).all():
                    raise RuntimeError(f"independent plaintext reference has invalid output: {info['name']}")
                expected[info["name"]] = value
            plain = client/f"case-{index}.input.bin"
            input_path = server/f"case-{index}.input.ct"
            _write_values(plain, flat)
            _invoke([trusted, "encrypt", client, server, plain, input_path], config, logs/f"case-{index}.encrypt.log")
            input_hash = digest(input_path)
            decoded, records = {}, {}
            for label, runner in (("reference", trusted), ("candidate", candidate_runner)):
                cipher = server/f"case-{index}.{label}.output.ct"
                records[label] = evaluate(runner, input_path, cipher, f"case-{index}.{label}.evaluate.log")
                output_path = client/f"case-{index}.{label}.output.bin"
                _invoke([trusted, "decrypt", client, cipher, output_path], config, logs/f"case-{index}.{label}.decrypt.log")
                decoded[label] = _outputs(output_path, manifest["outputs"])
                if digest(input_path) != input_hash:
                    raise RuntimeError("shared encrypted input changed during evaluation")
            if records["reference"]["counts"] != records["candidate"]["counts"]:
                raise RuntimeError("candidate operation counters differ from the frozen reference")
            errors = {}
            for info in manifest["outputs"]:
                key = info["name"]
                errors[key] = {
                    "candidate_vs_reference": _error(decoded["candidate"][key], decoded["reference"][key], policy["atol"], policy["rtol"]),
                    "candidate_vs_plaintext": _error(decoded["candidate"][key], expected[key], policy["atol"], policy["rtol"]),
                    "reference_vs_plaintext": _error(decoded["reference"][key], expected[key], policy["atol"], policy["rtol"]),
                }
            case_report = {"name": name, "input_ciphertext_sha256": input_hash, "outputs": errors,
                           "reference_runtime": records["reference"], "candidate_runtime": records["candidate"],
                           "counts_match": True, "passed": all(check["passed"] for error in errors.values() for check in error.values())}
            report["cases"].append(case_report)
            write_json(output/"report.json", report)
            if not case_report["passed"]:
                failed = [(key, pair, check) for key, pairs in errors.items()
                          for pair, check in pairs.items() if not check["passed"]]
                key, pair, check = failed[0]
                raise RuntimeError(f"case={name} output={key} comparison={pair} "
                    f"max_abs={check['max_abs_error']:.6g} max_relative={check['max_relative_error']:.6g} "
                    f"atol={policy['atol']:.6g} rtol={policy['rtol']:.6g}")
            integrity()
            last_input, last_counts = input_path, records["reference"]["counts"]
        report["functional_passed"] = True
        report["validation_performed"] = True
        report["policy_passed"] = not policy["insecure_demo"]
        stage = "measurement"
        measurements = {"reference": [], "candidate": []}
        for iteration in range(policy["warmups"]+policy["repetitions"]):
            order = (("reference", trusted), ("candidate", candidate_runner))
            if iteration % 2:
                order = tuple(reversed(order))
            for label, runner in order:
                value = evaluate(runner, last_input, server/f"timing-{label}.output.ct", f"timing-{iteration}.{label}.log")
                if value["counts"] != last_counts:
                    raise RuntimeError("timed evaluation counters differ from the validated computation")
                if iteration >= policy["warmups"]:
                    measurements[label].append(value)
        integrity()
        if digest(last_input) != report["cases"][-1]["input_ciphertext_sha256"]:
            raise RuntimeError("timed evaluation changed the frozen encrypted input")
        report["measurement"] = {
            "reference": _summary(measurements["reference"]), "candidate": _summary(measurements["candidate"]),
            "warmups": policy["warmups"], "repetitions": policy["repetitions"],
            "case": report["cases"][-1]["name"], "order": "alternating reference/candidate",
            "scope": "runner evaluator runtime.seconds; wall includes process and public-key loading",
            "memory_measured": False, "gpu_memory_measured": False,
        }
        report["measured"] = True
        report["status"] = "measured" if report["policy_passed"] else "functional_development_only"
        report["server_has_no_secret_key"] = not any("secret" in path.name.lower() for path in server.rglob("*"))
        if not report["server_has_no_secret_key"]:
            raise RuntimeError("server directory contains unexpected private-key material")
        write_json(output/"report.json", report)
        return report
    except Exception as error:
        report.update({"status": "rejected", "failed_stage": stage, "error": str(error),
                       "policy_passed": False, "selectable": False})
        write_json(output/"report.json", report)
        if isinstance(error, ValidationInfrastructureError):
            raise
        raise RuntimeError(f"encrypted validation failed at {stage}: {error}") from error
